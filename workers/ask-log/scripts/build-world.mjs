// Builds src/world.js: country outlines as SVG paths (Natural Earth projection), keyed by
// ISO 3166-1 alpha-2 (the code Cloudflare puts in request.cf.country).
//
//   curl -o countries-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json
//   curl -o codes.json https://cdn.jsdelivr.net/npm/i18n-iso-countries@7.11.0/codes.json
//   node scripts/build-world.mjs countries-110m.json codes.json > src/world.js
//
// The dashboard projects city dots with the same formula (see project() in dashboard.js),
// so keep W, H and SCALE in sync with it.
import { readFileSync } from 'node:fs';

const [topoFile, codesFile] = process.argv.slice(2);
const topo = JSON.parse(readFileSync(topoFile, 'utf8'));
const codes = JSON.parse(readFileSync(codesFile, 'utf8'));
const byNumeric = Object.fromEntries(codes.map(([a2, , num]) => [num, a2]));
const NO_ID = { Kosovo: 'XK', 'N. Cyprus': 'CY', Somaliland: 'SO' };

export const W = 960, H = 470, SCALE = 170;

export function project(lon, lat) {
    const l = lon * Math.PI / 180, p = lat * Math.PI / 180, p2 = p * p, p4 = p2 * p2;
    const x = l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)));
    const y = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)));
    return [W / 2 + x * SCALE, H / 2 - y * SCALE + 18];
}

// Decode the quantized, delta-encoded arcs into lon/lat points.
const [sx, sy] = topo.transform.scale, [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * sx + tx, y * sy + ty]; });
});
function ring(indexes) {
    const pts = [];
    for (const i of indexes) {
        const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
        pts.push(...(pts.length ? a.slice(1) : a));
    }
    return pts;
}
// Rings that cross the 180° meridian (Russia's far east, Fiji) would streak across the whole
// map; unwrap them so longitudes run on continuously, then shift the ring back near the map.
function unwrap(pts) {
    const out = [pts[0].slice()];
    for (let i = 1; i < pts.length; i++) {
        let lon = pts[i][0];
        const prev = out[i - 1][0];
        while (lon - prev > 180) lon -= 360;
        while (lon - prev < -180) lon += 360;
        out.push([lon, pts[i][1]]);
    }
    const mean = out.reduce((s, p) => s + p[0], 0) / out.length;
    const shift = mean > 180 ? -360 : mean < -180 ? 360 : 0;
    return shift ? out.map(([lon, lat]) => [lon + shift, lat]) : out;
}
function ringPath(pts) {
    pts = unwrap(pts);
    let d = '', last = '';
    for (const [lon, lat] of pts) {
        const [x, y] = project(lon, lat);
        const s = `${Math.round(x * 10) / 10},${Math.round(y * 10) / 10}`;
        if (s === last) continue;
        d += (d ? 'L' : 'M') + s;
        last = s;
    }
    return d + 'Z';
}

const out = [];
for (const g of topo.objects.countries.geometries) {
    const name = g.properties.name;
    if (name === 'Antarctica') continue;
    const code = byNumeric[g.id] || NO_ID[name] || '';
    const polys = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
    const d = polys.map((poly) => poly.map((r) => ringPath(ring(r))).join('')).join('');
    if (d) out.push([code, name, d]);
}

process.stdout.write(`// Generated by scripts/build-world.mjs from world-atlas@2.0.2 (Natural Earth 1:110m, public domain).
// [ISO alpha-2, name, SVG path] in a ${W}x${H} Natural Earth projection. Do not edit by hand.
export const WORLD = { w: ${W}, h: ${H}, scale: ${SCALE}, countries: ${JSON.stringify(out)} };
`);
